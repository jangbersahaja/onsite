const MAX_DEVICE_NAME_LENGTH = 80;

export function describeDeviceFromUserAgent(userAgent: string | null) {
  const ua = userAgent?.trim();
  if (!ua) return null;

  const platform = /iPhone/.test(ua)
    ? "iPhone"
    : /iPad/.test(ua)
      ? "iPad"
      : /Android/.test(ua)
        ? "Android"
        : /Windows/.test(ua)
          ? "Windows"
          : /Macintosh/.test(ua)
            ? "Mac"
            : /CrOS/.test(ua)
              ? "ChromeOS"
              : /Linux/.test(ua)
                ? "Linux"
                : null;

  const browser = /Edg\//.test(ua)
    ? "Edge"
    : /OPR\//.test(ua)
      ? "Opera"
      : /Firefox\/|FxiOS\//.test(ua)
        ? "Firefox"
        : /Chrome\/|CriOS\//.test(ua)
          ? "Chrome"
          : /Safari\//.test(ua)
            ? "Safari"
            : null;

  const name = [platform, browser].filter(Boolean).join(" · ");
  return name ? name.slice(0, MAX_DEVICE_NAME_LENGTH) : null;
}
